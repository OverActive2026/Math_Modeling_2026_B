function [dx, out] = pemfc_rhs_mvp(t, x, u, p, g, s)

% PEMFC 一维瞬态模型的右端函数 —— 无冰 MVP 版本
%
% -------------------------------------------------------------------------
% 状态方程：
%
%       dx/dt = f(t,x,u)
%
%
% 状态向量：
%
%       x =
%       [
%           T       温度场
%           cH2     阳极侧氢气浓度
%           cO2     阴极侧氧气浓度
%           mw      总水质量浓度
%           mi      冰质量浓度（MVP中固定为0）
%       ]
%
%
% 当前 MVP 包括：
%
%   1. H2 一维扩散 + 电化学消耗
%   2. O2 一维扩散 + 电化学消耗
%   3. 总水扩散 + 电渗拖曳 + 阴极产水
%   4. Nernst + 活化 + 欧姆 + 浓差极化
%   5. 一维热传导
%   6. 两端对流散热
%   7. 电化学反应产热
%
%
% 当前 MVP 暂不包括：
%
%   1. 水/冰相变
%   2. 冻结潜热
%   3. 冰占孔
%   4. 冰覆盖催化活性面积
%   5. 动态孔隙率储气项 d(eps*c)/dt
%
%
% INPUT
% -----
%
% t :
%       当前时间 [s]
%
% x :
%       ODE 状态向量
%
% u :
%       输入结构体
%
%       u.j
%           外部加载电流密度 [A/m^2]
%
%       u.Tamb
%           环境温度 [K]
%
%       u.qaux
%           辅助体积热源 [W/m^3]
%
%           Q1 MVP 中令：
%
%               u.qaux = 0
%
%
% p :
%       pemfc_params()
%
% g :
%       build_grid()
%
% s :
%       build_state_index()
%
%
% OUTPUT
% ------
%
% dx :
%       状态导数
%
% out :
%       调试和后处理用输出
%
%       out.Vcell
%       out.Tavg
%       out.cH2_aCL
%       out.cO2_cCL
%       out.lambdaMean
%       out.jLim
%       out.qgen
%       out.water
%       out.voltage
%
%
% IMPORTANT
% ---------
%
% 本函数主要用于第一阶段模型联调。
% 最终冷启动模型将在此基础上继续加入冰相动力学。
%

%% ========================================================================
% 0. 输入检查
% ========================================================================

if numel(x) ~= s.Nx
    error('pemfc_rhs_mvp:StateSizeMismatch', ...
        'x length (%d) does not equal s.Nx (%d).', ...
        numel(x),s.Nx);
end


% -------------------------------------------------------------------------
% 外部加载电流密度
% -------------------------------------------------------------------------

if ~isfield(u,'j')
    error('Input u must contain field u.j.');
end

j = u.j;


% -------------------------------------------------------------------------
% 环境温度
% -------------------------------------------------------------------------

if ~isfield(u,'Tamb')
    error('Input u must contain field u.Tamb.');
end

Tamb = u.Tamb;


% -------------------------------------------------------------------------
% 辅助加热
%
% Q1 暂时没有辅助加热，因此默认 = 0
% -------------------------------------------------------------------------

if ~isfield(u,'qaux') || isempty(u.qaux)

    qaux = zeros(g.N,1);

elseif isscalar(u.qaux)

    qaux = u.qaux .* ones(g.N,1);

else

    qaux = u.qaux(:);

    if numel(qaux) ~= g.N
        error('u.qaux must be scalar or contain g.N values.');
    end

end


%% ========================================================================
% 1. 从总状态向量中拆出各物理状态
% ========================================================================
%
% build_state_index() 已经定义好了：
%
%   T      : 全区域
%   H2     : aGDL + aCL
%   O2     : cCL + cGDL
%   mw     : 全区域
%   mi     : 多孔区域
%

T   = x(s.idx.T);

cH2 = x(s.idx.H2);

cO2 = x(s.idx.O2);

mw  = x(s.idx.mw);

mi  = x(s.idx.mi);


%% ========================================================================
% 2. MVP 中冰状态强制不参与动力学
% ========================================================================
%
% 当前阶段 mi 只是为了保持状态向量结构与未来完整模型一致。
%
% 如果初始条件正确：
%
%       mi(0) = 0
%
% 那么：
%
%       dmi/dt = 0
%
% 会保证全过程 mi = 0。
%

dmi = zeros(size(mi));


%% ========================================================================
% 3. 电化学反应源项
% ========================================================================
%
% 根据法拉第定律：
%
% aCL:
%
%       SH2 = -j/(2 F LaCL)
%
%
% cCL:
%
%       SO2 = -j/(4 F LcCL)
%
%       Sw  = Mw*j/(2 F LcCL)
%
%
% calc_reaction_sources 返回的是“全局网格”上的源项。
%

[src, rxnInfo] = ...
    calc_reaction_sources(j,g,p);


%% ========================================================================
% 4. 水迁移
% ========================================================================
%
% calc_water_flux 内部已经完成：
%
%   1. 蒸气/液水平衡
%
%   2. porous region:
%
%          Dw,eff
%
%   3. PEM:
%
%          lambda
%          Dw,mem
%
%   4. 扩散水通量
%
%          Ndiff = -Dw*d(mw)/dx
%
%   5. 电渗拖曳
%
%          Neod = nd*Mw*im/F
%
%   6. 总水通量
%
%          Nw = Ndiff + Neod
%

[Nw, waterOut] = ...
    calc_water_flux( ...
        T, ...
        mw, ...
        j, ...
        g, ...
        p);


%% ========================================================================
% 5. 总水守恒
% ========================================================================
%
% 题目：
%
%       dmw/dt =
%       -dNw/dx + Sw
%
%
% flux_divergence_fv 返回的定义就是：
%
%       -dNw/dx
%

divNw = ...
    flux_divergence_fv( ...
        Nw, ...
        g, ...
        (1:g.N).' ...
        );


dmw = ...
    divNw + src.Sw;


%% ========================================================================
% 6. 当前气相孔隙率
% ========================================================================
%
% waterOut.eps_g 已经考虑：
%
%       eps_g =
%       eps0 - eps_liquid
%
%
% 当前没有冰：
%
%       eps_ice = 0
%
% 这个 eps_g 会用于修正气体有效扩散系数。
%

eps_g = ...
    waterOut.eps_g;


%% ========================================================================
% 7. 建立干孔隙率 eps0 的全局空间分布
% ========================================================================
%
% MVP 的一个重要简化：
%
% 气体方程原式是：
%
%       d(eps_g*c)/dt = diffusion + source
%
%
% 完整展开应该是：
%
%       eps_g*dc/dt
%       + c*deps_g/dt
%       =
%       diffusion + source
%
%
% 但第一版为了先验证模型结构，我们采用：
%
%       eps0*dc/dt =
%       diffusion + source
%
%
% 即：
%
%   - 扩散系数仍然感受到液水堵塞
%   - 气体存储项暂时使用干孔隙率 eps0
%
% 完整冰模型时会重新处理这一项。
%

eps0Full = zeros(g.N,1);

for k = 1:5

    idxLayer = find(g.layerId == k);

    eps0Full(idxLayer) = ...
        p.mat.eps0(k);

end


%% ========================================================================
% 8. H2 有效扩散系数
% ========================================================================
%
% H2 只存在于：
%
%       aGDL + aCL
%

idxH2 = ...
    g.idx_H2;


DH2 = ...
    calc_gas_diffusivity( ...
        p.trans.DH2_ref, ...
        T(idxH2), ...
        p.bc.pAnode, ...
        eps_g(idxH2), ...
        p);


%% ========================================================================
% 9. H2 边界条件
% ========================================================================
%
% 左端：
%
%       阳极气体入口
%
%       cH2,in =
%       xH2 * pAnode / (R*T)
%
%
% 右端：
%
%       aCL / PEM
%
%       H2 不能穿透质子交换膜
%
%       JH2 = 0
%

bcH2.left.type = 'dirichlet';

bcH2.left.value = ...
    p.bc.xH2 .* ...
    p.bc.pAnode ./ ...
    (p.const.R .* T(g.idx_aGDL(1)));


bcH2.right.type = 'noflux';


%% ========================================================================
% 10. H2 扩散项
% ========================================================================

[diffH2, JH2] = ...
    diffusion_fv( ...
        cH2, ...
        DH2, ...
        g, ...
        idxH2, ...
        bcH2);


%% ========================================================================
% 11. H2 守恒
% ========================================================================
%
% MVP:
%
%       eps0 * dcH2/dt =
%       d/dx(D*dC/dx) + SH2
%

epsH2_storage = ...
    eps0Full(idxH2);


if any(epsH2_storage <= 0)

    error('Invalid H2 storage porosity.');

end


dcH2 = ...
    ( ...
      diffH2 ...
      + src.SH2(idxH2) ...
    ) ./ ...
    epsH2_storage;


%% ========================================================================
% 12. O2 有效扩散系数
% ========================================================================
%
% O2 只存在于：
%
%       cCL + cGDL
%

idxO2 = ...
    g.idx_O2;


DO2 = ...
    calc_gas_diffusivity( ...
        p.trans.DO2_ref, ...
        T(idxO2), ...
        p.bc.pCathode, ...
        eps_g(idxO2), ...
        p);


%% ========================================================================
% 13. O2 边界条件
% ========================================================================
%
% 我们定义：
%
%       +x : 阳极 -> 阴极
%
%
% 因此 O2 transport domain：
%
%       PEM | cCL | cGDL | air
%
%
% 左端：
%
%       PEM/cCL
%
%       O2 无法穿膜
%
%       JO2 = 0
%
%
% 右端：
%
%       阴极空气入口
%
%       Dirichlet O2 concentration
%

bcO2.left.type = 'noflux';


bcO2.right.type = 'dirichlet';

bcO2.right.value = ...
    p.bc.xO2 .* ...
    p.bc.pCathode ./ ...
    (p.const.R .* T(g.idx_cGDL(end)));


%% ========================================================================
% 14. O2 扩散项
% ========================================================================

[diffO2, JO2] = ...
    diffusion_fv( ...
        cO2, ...
        DO2, ...
        g, ...
        idxO2, ...
        bcO2);


%% ========================================================================
% 15. O2 守恒
% ========================================================================

epsO2_storage = ...
    eps0Full(idxO2);


if any(epsO2_storage <= 0)

    error('Invalid O2 storage porosity.');

end


dcO2 = ...
    ( ...
      diffO2 ...
      + src.SO2(idxO2) ...
    ) ./ ...
    epsO2_storage;


%% ========================================================================
% 16. 提取催化层代表性 H2 / O2 状态
% ========================================================================
%
% 电压模型需要：
%
%       pH2 at aCL
%       pO2 at cCL
%
%
% 我们不取某一个孤立节点，而采用催化层厚度加权平均。
%
% 这样网格改变以后，结果更稳定。
%


% -------------------------------------------------------------------------
% aCL 中 H2
% -------------------------------------------------------------------------

localH2_aCL = ...
    s.local.H2_aCL;

cH2_aCL_vec = ...
    cH2(localH2_aCL);

T_aCL_vec = ...
    T(g.idx_aCL);

dx_aCL = ...
    g.dx(g.idx_aCL);


cH2_aCL = ...
    sum(cH2_aCL_vec .* dx_aCL) ./ ...
    sum(dx_aCL);


T_aCL = ...
    sum(T_aCL_vec .* dx_aCL) ./ ...
    sum(dx_aCL);


% -------------------------------------------------------------------------
% cCL 中 O2
% -------------------------------------------------------------------------

localO2_cCL = ...
    s.local.O2_cCL;

cO2_cCL_vec = ...
    cO2(localO2_cCL);

T_cCL_vec = ...
    T(g.idx_cCL);

dx_cCL = ...
    g.dx(g.idx_cCL);


cO2_cCL = ...
    sum(cO2_cCL_vec .* dx_cCL) ./ ...
    sum(dx_cCL);


T_cCL = ...
    sum(T_cCL_vec .* dx_cCL) ./ ...
    sum(dx_cCL);


%% ========================================================================
% 17. 计算催化层代表性分压
% ========================================================================
%
% 理想气体：
%
%       p = c R T
%

pH2 = ...
    cH2_aCL .* ...
    p.const.R .* ...
    T_aCL;


pO2 = ...
    cO2_cCL .* ...
    p.const.R .* ...
    T_cCL;


%% ========================================================================
% 18. 计算单电池代表温度
% ========================================================================
%
% 电压模型中使用一个代表性的 cell temperature。
%
% 第一版采用沿厚度方向体积平均：
%
%       Tavg =
%       integral(T dx) / L
%

Tavg = ...
    sum(T .* g.dx) ./ ...
    sum(g.dx);


%% ========================================================================
% 19. 阴极催化层代表性 O2 扩散系数
% ========================================================================
%
% calc_cell_voltage 中极限电流密度需要：
%
%       DO2_eff
%       cO2,cCL
%
% 因此取 cCL 中的厚度加权平均值。
%

DO2_cCL_vec = ...
    DO2(s.local.O2_cCL);


DO2_cCL = ...
    sum(DO2_cCL_vec .* dx_cCL) ./ ...
    sum(dx_cCL);


%% ========================================================================
% 20. PEM 代表性含水量
% ========================================================================
%
% calc_water_flux 已经给出了：
%
%       lambdaMean
%
% 即 PEM 内沿厚度平均含水量。
%

lambdaMean = ...
    waterOut.lambdaMean;


%% ========================================================================
% 21. 阴极等效扩散距离
% ========================================================================
%
% 这个参数在题面没有唯一规定。
%
% 我们要求它提前在 pemfc_params 中设置好。
%
% MVP 建议暂时：
%
%       Ldiff = LcCL + LcGDL
%

if ~isfinite(p.echem.Ldiff) || p.echem.Ldiff <= 0

    error('pemfc_rhs_mvp:MissingLdiff', ...
        ['p.echem.Ldiff has not been assigned. ', ...
         'For MVP, set e.g. ', ...
         'p.echem.Ldiff = p.geom.LcCL + p.geom.LcGDL;']);

end


%% ========================================================================
% 22. 单电池电压
% ========================================================================
%
% 包括：
%
%       Erev
%       eta_activation
%       eta_ohmic
%       eta_concentration
%

[Vcell, voltageOut] = ...
    calc_cell_voltage( ...
        Tavg, ...
        pH2, ...
        pO2, ...
        j, ...
        lambdaMean, ...
        DO2_cCL, ...
        cO2_cCL, ...
        p.echem.Ldiff, ...
        p);


%% ========================================================================
% 23. 热物性
% ========================================================================
%
% MVP 使用题目给出的等效均质热模型：
%
%       rhoCp_eff
%       k_eff
%

[rhoCp, kEff, thermalPropOut] = ...
    calc_thermal_properties(g,p);


%% ========================================================================
% 24. 一维热传导 + 两端对流散热
% ========================================================================

[qCond, qHeatFace, thermalFVOut] = ...
    heat_conduction_fv( ...
        T, ...
        kEff, ...
        Tamb, ...
        p.thermal.h, ...
        g);


%% ========================================================================
% 25. 电化学反应产热
% ========================================================================
%
% 题目：
%
%       qgen =
%       j * (Eth - Vcell) / Lcell
%
%
% 单位：
%
%       A/m^2 * V / m
%
%       = W/m^3
%
%
% MVP 中先认为该体积热源均匀分布在整个一维区域。
%

qgenScalar = ...
    j .* ...
    (p.echem.Eth - Vcell) ./ ...
    p.geom.Lcell;


qgen = ...
    qgenScalar .* ...
    ones(g.N,1);


%% ========================================================================
% 26. 温度状态方程
% ========================================================================
%
% 能量守恒：
%
%       rhoCp * dT/dt =
%
%       qCond
%       + qgen
%       + qaux
%
%
% 因此：
%
%       dT/dt =
%
%       (qCond + qgen + qaux)/rhoCp
%

dT = ...
    ( ...
      qCond ...
      + qgen ...
      + qaux ...
    ) ./ ...
    rhoCp;


%% ========================================================================
% 27. 打包状态导数
% ========================================================================

dx = zeros(s.Nx,1);


dx(s.idx.T) = ...
    dT;


dx(s.idx.H2) = ...
    dcH2;


dx(s.idx.O2) = ...
    dcO2;


dx(s.idx.mw) = ...
    dmw;


dx(s.idx.mi) = ...
    dmi;


%% ========================================================================
% 28. 可选诊断输出
% ========================================================================
%
% ode15s 实际积分时只使用第一个输出 dx。
%
% out 非常适合：
%
%   - 手动调用 RHS 调试
%   - 后处理
%   - 以后转 S-Function
%

if nargout > 1

    out.t = t;

    out.j = j;

    out.Tamb = Tamb;


    % ---------------------------------------------------------------------
    % 电压
    % ---------------------------------------------------------------------

    out.Vcell = Vcell;

    out.voltage = voltageOut;


    % ---------------------------------------------------------------------
    % 温度
    % ---------------------------------------------------------------------

    out.Tavg = Tavg;

    out.Tmin = min(T);

    out.Tmax = max(T);

    out.dT = dT;


    % ---------------------------------------------------------------------
    % 气体
    % ---------------------------------------------------------------------

    out.cH2_aCL = cH2_aCL;

    out.cO2_cCL = cO2_cCL;

    out.pH2 = pH2;

    out.pO2 = pO2;

    out.DH2 = DH2;

    out.DO2 = DO2;

    out.JH2 = JH2;

    out.JO2 = JO2;


    % ---------------------------------------------------------------------
    % 水
    % ---------------------------------------------------------------------

    out.water = waterOut;

    out.Nw = Nw;

    out.dmw = dmw;

    out.lambdaMean = lambdaMean;


    % ---------------------------------------------------------------------
    % 反应
    % ---------------------------------------------------------------------

    out.reaction = rxnInfo;

    out.sources = src;


    % ---------------------------------------------------------------------
    % 热
    % ---------------------------------------------------------------------

    out.qgen = qgenScalar;

    out.qCond = qCond;

    out.qHeatFace = qHeatFace;

    out.thermalProperties = thermalPropOut;

    out.thermalFV = thermalFVOut;


    % ---------------------------------------------------------------------
    % 最有用的几个健康指标
    % ---------------------------------------------------------------------

    out.jLim = voltageOut.jLim;

    out.transportValid = ...
        voltageOut.transportValid;

    out.minH2 = min(cH2);

    out.minO2 = min(cO2);

    out.minMw = min(mw);

end

end